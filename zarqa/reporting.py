"""Reports: the brief (what came in over a period, most relevant first) and a report on one document.

Markdown, or HTML built from it, both self-contained. Every line points back to a document or entity id, so a
reader can check it in Zarqa.
"""

from __future__ import annotations

import html
import re
from datetime import datetime, timedelta, timezone
from typing import Any

from .intel.store import INDICATOR_TYPES, KnowledgeStore


def _since(days: float) -> str:
    return (datetime.now(timezone.utc) - timedelta(days=days)).isoformat(timespec="seconds")


def brief_data(cfg, store: KnowledgeStore, *, days: float = 1.0, top: int = 10) -> dict[str, Any]:
    since = _since(days)
    docs = [d for d in store.documents(limit=2000) if d["fetched"] >= since and d["kind"] not in ("list", "stix")]
    scored = sorted([d for d in docs if d["relevance"] is not None], key=lambda d: (-d["relevance"], -d["id"]))
    new_ents = [e for e in store.entities(limit=5000, order="first_seen") if e["first_seen"] >= since]
    by_type: dict[str, list[dict]] = {}
    for e in new_ents:
        by_type.setdefault(e["type"], []).append(e)
    kev = [e for e in store.entities(etype="cve", limit=2000, order="last_seen")
           if e["last_seen"] >= since and "kev" in e["tags"]]
    out: dict[str, Any] = {
        "period_days": days, "since": since, "generated": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "instance": cfg.instance_name if cfg is not None else "Zarqa", "documents": len(docs),
        "top": scored[:top] if scored else docs[:top], "scored": bool(scored),
        "new": {k: v[:25] for k, v in by_type.items()}, "new_counts": {k: len(v) for k, v in by_type.items()},
        "kev": kev[:25], "review": [d for d in docs if d.get("review")][:10], "requirements": {},
    }
    for d in docs:
        for t in d["tags"]:
            if t.startswith("pir:"):
                out["requirements"].setdefault(t[4:], []).append(d)
    try:
        from .brand.watch import store_for as bstore
        out["brand"] = [f for f in bstore(cfg).findings(limit=200) if f["first_seen"] >= since][:15]
    except Exception:
        out["brand"] = []
    try:
        from .investigate.store import store_for as istore
        out["investigations"] = [i for i in istore(cfg).list(limit=200) if i["created"] >= since and i["status"] == "done"]
    except Exception:
        out["investigations"] = []
    return out


def _md_escape(s: str) -> str:
    return re.sub(r"([\\`*_\[\]<>|])", r"\\\1", str(s or "")).replace("\n", " ")


def brief_markdown(b: dict) -> str:
    e = _md_escape
    lines = [f"# {e(b['instance'])} brief", "",
             f"{b['documents']} documents in the last {b['period_days']:g} day(s), generated {b['generated'][:16]} UTC.", ""]
    lines += ["## Most relevant" if b["scored"] else "## Latest (no organization profile, so not ranked)", ""]
    if not b["top"]:
        lines.append("Nothing new.")
    for d in b["top"]:
        rel = f"**{d['relevance']}** " if d["relevance"] is not None else ""
        lines.append(f"- {rel}{e(d['title'])} (document {d['id']}, {e(d['source'])})")
        if d.get("summary"):
            lines.append(f"  {e(d['summary'])}")
        if d.get("relevance_reason"):
            lines.append(f"  Why: {e(d['relevance_reason'])}")
    if b["requirements"]:
        lines += ["", "## Your requirements", ""]
        for name, ds in b["requirements"].items():
            lines.append(f"- **{e(name)}**: " + "; ".join(f"{e(d['title'])} (document {d['id']})" for d in ds[:5]))
    named = [t for t in ("actor", "campaign", "malware", "tool") if t in b["new"]]
    if named:
        lines += ["", "## New names", ""]
        for t in named:
            lines.append(f"- {t}: " + ", ".join(e(x["display"]) for x in b["new"][t][:15])
                         + (f" and {b['new_counts'][t] - 15} more" if b["new_counts"][t] > 15 else ""))
    inds = {t: n for t, n in b["new_counts"].items() if t in INDICATOR_TYPES}
    if inds:
        lines += ["", "## New indicators", "", ", ".join(f"{n} {t}" for t, n in sorted(inds.items()))]
    if b["kev"]:
        lines += ["", "## Known exploited CVEs mentioned", "", ", ".join(e(x["display"]) for x in b["kev"])]
    if b["brand"]:
        lines += ["", "## New lookalike domains", ""]
        lines += [f"- **{f['score']}** {e(f['domain'])} ({e(f['technique'])}, of {e(f['watched'])})" for f in b["brand"]]
    if b["investigations"]:
        lines += ["", "## Investigations", ""]
        lines += [f"- {e(i['question'])}: {e(i['outcome'])} (confidence {i['confidence']}, investigation {i['id']})"
                  for i in b["investigations"]]
    if b["review"]:
        lines += ["", "## For review", ""]
        lines += [f"- {e(d['title'])} (document {d['id']}): {e(d['review'])}" for d in b["review"]]
    lines += ["", "---", "Generated by Zarqa. Model summaries and labels can be wrong; check the cited documents."]
    return "\n".join(lines) + "\n"


def document_markdown(store: KnowledgeStore, doc_id: int) -> str:
    e = _md_escape
    d = store.document(doc_id, with_text=False)
    if not d:
        raise ValueError("no such document")
    lines = [f"# {e(d['title'])}", "", f"Source: {e(d['source'])}" + (f", {e(d['url'])}" if d["url"] else ""),
             f"Collected {d['fetched'][:16]} UTC" + (f", published {e(d['published'])}" if d["published"] else ""), ""]
    if d["summary"]:
        lines += ["## Summary", "", e(d["summary"]), ""]
    if d["relevance"] is not None:
        lines += [f"Relevance to you: **{d['relevance']}**. {e(d['relevance_reason'])}", ""]
    seen: dict[str, dict[str, dict]] = {}
    for m in store.mentions(document_id=doc_id, limit=1000):
        seen.setdefault(m["type"], {}).setdefault(m["display"], m)
    for t, vals in sorted(seen.items()):
        lines += [f"## {t}", ""]
        for v, m in vals.items():
            role = f" ({m['context']})" if m["context"] else ""
            lines.append(f"- `{v}`{role}" + (f": \"{e(m['snippet'])}\"" if m["snippet"] else ""))
        lines.append("")
    rels = store.relations(document_id=doc_id)
    if rels:
        lines += ["## Relations", ""]
        lines += [f"- {e(r['src_display'])} {r['rel'].replace('_', ' ')} {e(r['dst_display'])}: \"{e(r['snippet'])}\""
                  for r in rels]
    return "\n".join(lines) + "\n"


def to_html(md: str, title: str = "Zarqa") -> str:
    """A small, safe Markdown subset to HTML (headings, lists, bold, code); everything is escaped first."""
    out, in_list = [], False
    for raw in md.splitlines():
        line = html.escape(raw.replace("\\", ""))
        line = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", line)
        line = re.sub(r"`(.+?)`", r"<code>\1</code>", line)
        if line.startswith("- "):
            if not in_list:
                out.append("<ul>")
                in_list = True
            out.append(f"<li>{line[2:]}</li>")
            continue
        if in_list and not raw.startswith("  "):
            out.append("</ul>")
            in_list = False
        if raw.startswith("  ") and out and out[-1].startswith("<li>"):
            out[-1] = out[-1][:-5] + f"<br><span class=m>{line.strip()}</span></li>"
        elif line.startswith("# "):
            out.append(f"<h1>{line[2:]}</h1>")
        elif line.startswith("## "):
            out.append(f"<h2>{line[3:]}</h2>")
        elif line == "---":
            out.append("<hr>")
        elif line.strip():
            out.append(f"<p>{line}</p>")
    if in_list:
        out.append("</ul>")
    css = ("body{font:15px/1.55 system-ui,sans-serif;max-width:860px;margin:2rem auto;padding:0 1rem;color:#1d2330}"
           "h1{font-size:1.5rem}h2{font-size:1.1rem;margin-top:1.6rem;border-bottom:1px solid #ddd}"
           "code{background:#f2f4f7;padding:0 .2rem}.m{color:#5b6475;font-size:.9rem}li{margin:.3rem 0}")
    return (f"<!doctype html><html><head><meta charset=utf-8><title>{html.escape(title)}</title>"
            f"<style>{css}</style></head><body>{''.join(out)}</body></html>")
